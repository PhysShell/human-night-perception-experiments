#!/usr/bin/env python3
"""D0 summary tables from d0/results/tables/metrics.jsonl (descriptive, no score, no ranking).
  python3 d0/summarize.py -> d0/results/tables/summary.md, metrics_S*.csv
"""
import csv, json

T = "d0/results/tables"
rows = [json.loads(l) for l in open(f"{T}/metrics.jsonl")]
ref = {r["scene"]: r for r in json.load(open(f"{T}/scene_reference.json"))}
PRIMARY = [("pcond", "native_default"), ("pcond", "target_SDR200"), ("pcond", "target_BRIGHT500"),
           ("controls", "d1a_photometric"), ("controls", "d1b_key018"), ("reinhard02", "defaults"),
           ("mantiuk08", "native_default"), ("mantiuk08", "target_whiteauto"), ("mantiuk08", "target_whiteanchor"),
           ("mantiuk08", "sens_desktop"), ("mantiuk08", "sens_dim"), ("mantiuk08", "sens_sceneadapt_auto"),
           ("aces2", "DOCUMENTED_TARGET_CONFIG"),
           ("icam06", "native_default"), ("icam06", "target_abs_dark_readme"), ("icam06", "target_abs_dark_paper")]


def g(r, k, fmt="{:.3g}"):
    v = r.get(k)
    if v is None:
        return "–"
    if isinstance(v, list):
        return "(" + ", ".join(f"{x:.3f}" for x in v) + ")"
    return fmt.format(v)


def pick(scene, lum=None, extra=()):
    out = []
    for d, c in list(PRIMARY) + list(extra):
        for r in rows:
            if r["donor"] == d and r["config"] == c and r["scene"] == scene and (lum is None or r["lum"] == lum):
                out.append(r)
    return out


md = ["# D0 summary tables (generated by d0/summarize.py; descriptive only, no ranking)", "",
      "All values are light emitted by the parametric display (cd/m²) decoded with `d0/display_model.py`; `SCENE` rows are the physical scene. "
      "P_det is HDR-VDP-3 side-by-side detection of the bar: a diagnostic under HDR-VDP's observer model, not a human probability.", ""]


def table(title, scene, cols, lum=None, extra=(), with_ref=True):
    md.append(f"## {title}"); md.append("")
    md.append("| donor / config | scenario | " + " | ".join(c[0] for c in cols) + " |")
    md.append("|---|---|" + "---|" * len(cols))
    if with_ref and scene in ref:
        md.append("| **SCENE (physical)** | – | " + " | ".join(g(ref[scene], c[1]) for c in cols) + " |")
    for r in pick(scene, lum, extra):
        md.append(f"| {r['donor']} / {r['config']} | {r['geom']}_{r['lum']}_{r['amb']} | " + " | ".join(g(r, c[1]) for c in cols) + " |")
    md.append("")


NIGHT = [("sky median", "sky_median"), ("dark median", "dark_median"), ("dark log range", "dark_log_range"),
         ("% near black", "near_black_pct"), ("silhouette Weber", "silhouette_weber")]
SRC = [("peak", "peak"), ("% clipped", "clipped_pct"), ("plateau n", "plateau_n"), ("plateau ⌀ median ′", "plateau_diam_median_arcmin"),
       ("plateau ⌀ max ′", "plateau_diam_max_arcmin"), ("source/bg", "source_bg_contrast"), ("halo/bg", "halo_ratio"),
       ("lamp Δu′v′", "lamp_d_uv"), ("lamp sat. kept", "lamp_saturation_retention")]
USE = [("Y p0.1", "Y_p0.1"), ("Y p99.9", "Y_p99.9"), ("used log range", "used_log_range"), ("headroom", "headroom")]
table("S0 dark rural still: night appearance (P1, P2)", "S0", NIGHT + USE)
table("S1 still with lamp ribbon: night appearance (P1, P2)", "S1", NIGHT)
table("S1: bright sources and colour (P3, P5, P6)", "S1", SRC)
table("S1: display use (E)", "S1", USE)
table("S3 point source + bar: local visibility DIAGNOSTIC (P4)", "S3_bar",
      [("P_det EVAL_VIEWER", "P_det_bar_EVAL_VIEWER"), ("P_det EVAL_OFF", "P_det_bar_EVAL_OFF"), ("bar Weber (displayed)", "bar_weber_displayed"),
       ("peak", "peak"), ("plateau ⌀ max ′", "plateau_diam_max_arcmin"), ("halo/bg", "halo_ratio"), ("sky median", "sky_median")])
md.append("SCENE bar Weber contrast (physical, the bar is black on the 4e-4 cd/m² sky): " + g(ref["S3_bar"], "bar_weber_scene")); md.append("")
table("S4 real night photograph (Golden Gate): appearance", "S4", NIGHT[:4] + [("peak", "peak"), ("% clipped", "clipped_pct"), ("source/bg", "source_bg_contrast")] + USE[2:])
table("S5 mixed-luminance control (McKees Pub): appearance", "S5", NIGHT[:4] + [("peak", "peak"), ("% clipped", "clipped_pct")] + USE)

# sensitivity axes
md.append("## Sensitivity axes on S1 (PHONE, SDR100, DARK)"); md.append("")
md.append("| axis value | sky median | dark median | % near black | peak | plateau n | plateau ⌀ max ′ |"); md.append("|---|---|---|---|---|---|---|")
for r in sorted([r for r in rows if r["scene"] == "S1" and r["lum"] == "SDR100" and (r["config"].startswith("sens_whitey") or r["config"].startswith("SENSITIVITY_RUN"))],
                key=lambda r: (r["donor"], r["config"])):
    md.append(f"| {r['donor']} {r['config']} | {g(r, 'sky_median')} | {g(r, 'dark_median')} | {g(r, 'near_black_pct')} | {g(r, 'peak')} | {g(r, 'plateau_n')} | {g(r, 'plateau_diam_max_arcmin')} |")
md.append("")
# temporal
md.append("## S2 clip (2 s, 48 frames): temporal behaviour (P7)"); md.append("")
md.append("| donor / config | scenario | frames | mean max step | sky median max step | source-energy modulation | frames with isolated flash | tone-curve max step at scene p10 / p50 / p90 / p99 | sky median first → last |")
md.append("|---|---|---|---|---|---|---|---|---|")
for r in [r for r in rows if r["scene"] == "S2"]:
    t = r.get("tone_curve_max_step_rel_at_scene_levels_p10_p50_p90_p99") or r.get("tone_max_step_rel_at_scene_p10_p50_p90_p99") or []
    md.append(f"| {r['donor']} / {r['config']} | {r['geom']}_{r['lum']}_{r['amb']} | {r['frames']} | {r['mean_max_step_rel']:.3g} | {r['sky_median_max_step_rel']:.3g} | "
              f"{r['source_energy_modulation']:.3g} | {r['frames_with_isolated_flash']} | " + " / ".join(f"{x:.3g}" for x in t) +
              f" | {r['sky_median_first_last'][0]:.3g} → {r['sky_median_first_last'][1]:.3g} |")
md.append("")
# scenario change (P8)
md.append("## Changing the display (P8): S1 across luminance scenarios"); md.append("")
md.append("| donor / config | scenario | sky median | dark median | peak | % near black | plateau ⌀ max ′ | source/bg |"); md.append("|---|---|---|---|---|---|---|---|")
for d, c in [("pcond", "native_default"), ("pcond", "target_SDR200"), ("pcond", "target_BRIGHT500"), ("controls", "d1a_photometric"), ("controls", "d1b_key018"),
             ("reinhard02", "defaults"), ("mantiuk08", "target_whiteauto"), ("mantiuk08", "target_whiteanchor"), ("aces2", "DOCUMENTED_TARGET_CONFIG")]:
    for r in [r for r in rows if r["donor"] == d and r["config"] == c and r["scene"] == "S1"]:
        md.append(f"| {d} / {c} | {r['lum']} | {g(r, 'sky_median')} | {g(r, 'dark_median')} | {g(r, 'peak')} | {g(r, 'near_black_pct')} | {g(r, 'plateau_diam_max_arcmin')} | {g(r, 'source_bg_contrast')} |")
md.append("")
open(f"{T}/summary.md", "w").write("\n".join(md) + "\n")
for s in ("S0", "S1", "S3_bar", "S4", "S5", "S2"):
    sel = [r for r in rows if r["scene"] == s]
    keys = sorted({k for r in sel for k in r if not isinstance(r[k], (list, dict))})
    with open(f"{T}/metrics_{s}.csv", "w", newline="") as f:
        w = csv.DictWriter(f, keys, extrasaction="ignore"); w.writeheader(); [w.writerow(r) for r in sel]
print(f"{len(rows)} rows -> {T}/summary.md")
