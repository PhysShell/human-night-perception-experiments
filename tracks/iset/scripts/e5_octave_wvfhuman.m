% E4-E6 probe: can GNU Octave run the smallest ISETBio human-optics call?
% Run: octave --no-gui --eval "run('tracks/iset/scripts/e5_octave_wvfhuman.m')"
% Expects env ISET_CACHE = research-cache/iset (clones of isetcam, isetbio, isetvalidate).
root = getenv('ISET_CACHE');
warning('off','all');
addpath(genpath(fullfile(root,'isetcam')));
addpath(genpath(fullfile(root,'isetbio')));
warning('off','all'); % Octave emits many Matlab-compat warnings
printf('paths added\n');
steps = {
  'ieInit', ...
  'pkg load general; pkg load image; pkg load io; pkg load optiminterp; pkg load signal; pkg load statistics', ...
  'ieInitSession;', ...
  'wave = 400:10:700;', ...
  'wvf = wvfCreate(''wave'',wave);', ...
  'oi = oiCreate(''wvf human'',3);', ...
  'psf550 = oiGet(oi,''optics psf data'',550);', ...
  'scene = sceneCreate(''point array'');', ...
  'oi = oiCompute(oi,scene);', ...
  'save(''-v7'', fullfile(getenv(''ISET_OUT''),''oct_probe.mat''), ''psf550'');', ...
};
for k = 1:numel(steps)
  try
    eval(steps{k});
    printf('OK   %s\n', steps{k});
  catch err
    printf('FAIL %s\n  -> %s\n', steps{k}, err.message);
    for s = 1:min(numel(err.stack),6)
      printf('     at %s line %d (%s)\n', err.stack(s).name, err.stack(s).line, err.stack(s).file);
    end
  end
end
